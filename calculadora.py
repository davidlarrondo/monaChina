# Función para sumar dos números
def sumar(a, b):
    return a + b

# Función para restar dos números
def restar(a, b):
    return a - b

# Ejemplos de uso
resultado_suma = sumar(5, 3)   # 5 + 3 = 8
resultado_resta = restar(5, 3) # 5 - 3 = 2

print("Suma:", resultado_suma)
print("Resta:", resultado_resta)